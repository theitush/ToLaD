/**
 * OFFLINE generator for src/normal-table.ts (run: `node scripts/gen-normal-table.ts`).
 *
 * This script may use any float math: its output is committed as integers and is
 * the source of truth. The generation path only reads the integer table.
 *
 * Table: NORMAL_TABLE[j] = round(2^20 * Φ⁻¹(q_j)), j = 0..1024, with
 * q_j = j/1024 for 1 ≤ j ≤ 1023 and the ends clamped to q = 2^-33 / 1 − 2^-33.
 */
import { writeFileSync } from 'node:fs';

/** Φ(x) via Marsaglia's all-positive series (stable for |x| ≤ ~8). */
function Phi(x: number): number {
  let term = x;
  let sum = x;
  const x2 = x * x;
  for (let n = 1; n < 500; n++) {
    term *= x2 / (2 * n + 1);
    sum += term;
    if (Math.abs(term) < 1e-18 * Math.abs(sum)) break;
  }
  return 0.5 + sum * Math.exp(-0.5 * x2 - 0.91893853320467274178);
}

function invPhi(q: number): number {
  let lo = -9;
  let hi = 9;
  for (let i = 0; i < 200; i++) {
    const mid = (lo + hi) / 2;
    if (Phi(mid) < q) lo = mid;
    else hi = mid;
  }
  return (lo + hi) / 2;
}

const BUCKETS = 1024;
const SCALE = 1 << 20;
const out: number[] = [];
for (let j = 0; j <= BUCKETS; j++) {
  let q: number;
  if (j === 0) q = 2 ** -33;
  else if (j === BUCKETS) q = 1 - 2 ** -33;
  else q = j / BUCKETS;
  out.push(Math.round(invPhi(q) * SCALE));
}
// enforce exact antisymmetry
for (let j = 0; j <= BUCKETS / 2; j++) {
  const v = Math.round((out[BUCKETS - j]! - out[j]!) / 2);
  out[j] = -v;
  out[BUCKETS - j] = v;
}

const lines: string[] = [];
for (let i = 0; i < out.length; i += 8) lines.push('  ' + out.slice(i, i + 8).join(', ') + ',');
const src = `// GENERATED by scripts/gen-normal-table.ts — do not edit by hand.
/**
 * Inverse standard-normal CDF at 1025 knots, fixed point (×2^20), integers.
 * NORMAL_TABLE[j] = round(2^20·Φ⁻¹(j/1024)), ends clamped at q = 2^-33 (z ≈ ±6.33).
 */
export const NORMAL_TABLE_SCALE_BITS = 20;
export const NORMAL_TABLE_BUCKET_BITS = 10;
export const NORMAL_TABLE: Int32Array = Int32Array.from([
${lines.join('\n')}
]);
`;
writeFileSync(new URL('../src/normal-table.ts', import.meta.url), src);
console.log('wrote', out.length, 'entries; ends', out[0], out[BUCKETS], 'mid', out[512]);
